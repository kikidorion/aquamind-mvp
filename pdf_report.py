"""
AquaMind PDF Report Generator
Produces a branded, professional ESG water report using fpdf2.
"""

from fpdf import FPDF
from datetime import date
import json


# ── Brand colors (RGB) ──────────────────────────────────────────────────────
NAVY     = (13,  59,  102)   # deep navy
BLUE     = (21, 101, 192)    # strong blue
TEAL     = (0,  137, 123)    # teal accent
GRAY     = (96,  125, 139)   # gray text
LGRAY    = (245, 247, 250)   # light gray background
WHITE    = (255, 255, 255)
BLACK    = (26,  26,  46)    # near-black


class AquaMindReport(FPDF):
    def __init__(self, company_name: str, reporting_year: str):
        super().__init__()
        self.company_name = company_name
        self.reporting_year = reporting_year
        self.set_auto_page_break(auto=True, margin=20)
        self.set_margins(20, 20, 20)

    def header(self):
        if self.page_no() == 1:
            return
        # Header bar
        self.set_fill_color(*NAVY)
        self.rect(0, 0, 210, 12, "F")
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(*WHITE)
        self.set_xy(10, 3)
        self.cell(0, 6, "AQUAMIND  •  Water Intelligence Platform  •  CONFIDENTIAL", align="L")
        self.set_xy(0, 3)
        self.cell(200, 6, f"Page {self.page_no()}", align="R")
        self.set_text_color(*BLACK)
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "", 7)
        self.set_text_color(*GRAY)
        self.cell(0, 5, f"Generated by AquaMind AI Platform  •  {date.today().strftime('%B %d, %Y')}  •  aquamind.io", align="C")
        self.set_text_color(*BLACK)

    # ── Section helpers ──────────────────────────────────────────────────────

    def cover_page(self):
        self.add_page()
        # Navy header block
        self.set_fill_color(*NAVY)
        self.rect(0, 0, 210, 80, "F")

        # Teal accent bar
        self.set_fill_color(*TEAL)
        self.rect(0, 80, 210, 4, "F")

        self.set_text_color(*WHITE)
        self.set_font("Helvetica", "B", 36)
        self.set_xy(20, 20)
        self.cell(0, 14, "AQUAMIND", align="L")

        self.set_font("Helvetica", "", 13)
        self.set_xy(20, 36)
        self.cell(0, 8, "AI-Native Water Intelligence Platform", align="L")

        self.set_fill_color(*TEAL)
        self.rect(20, 47, 60, 1, "F")

        self.set_font("Helvetica", "B", 11)
        self.set_xy(20, 52)
        self.cell(0, 8, "Water Stewardship Report", align="L")

        self.set_font("Helvetica", "", 10)
        self.set_xy(20, 61)
        self.cell(0, 8, f"Reporting Year: {self.reporting_year}", align="L")
        self.set_xy(20, 69)
        self.cell(0, 8, f"Prepared for: {self.company_name}", align="L")

        # Body content
        self.set_text_color(*BLACK)
        self.set_xy(20, 95)
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(*GRAY)
        self.cell(0, 8, "FRAMEWORKS REFERENCED")
        self.ln(8)
        self.set_font("Helvetica", "", 10)
        self.set_text_color(*BLACK)
        frameworks = [
            "GRI Standard 303: Water and Effluents (2018)",
            "CDP Water Security Questionnaire",
            "TCFD Climate-Related Financial Disclosures",
            "EPA Safe Drinking Water Act (SDWA) Compliance",
            "EU Water Framework Directive",
        ]
        for f in frameworks:
            self.set_x(20)
            self.set_fill_color(*TEAL)
            self.rect(20, self.get_y() + 2, 3, 3, "F")
            self.set_x(26)
            self.cell(0, 7, f)
            self.ln(7)

        # Footer note on cover
        self.set_xy(20, 260)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(*GRAY)
        self.cell(0, 5, f"This report was generated by AquaMind's AI agent pipeline. Data analysis, quality monitoring,")
        self.ln(5)
        self.set_x(20)
        self.cell(0, 5, f"and ESG narrative were produced autonomously by specialized AI agents.")
        self.set_text_color(*BLACK)

    def section_title(self, title: str, subtitle: str = ""):
        self.set_fill_color(*NAVY)
        self.set_text_color(*WHITE)
        self.set_font("Helvetica", "B", 13)
        self.set_x(0)
        y = self.get_y()
        self.rect(0, y, 210, 10, "F")
        self.set_xy(20, y + 1.5)
        self.cell(0, 7, title.upper(), align="L")
        self.set_text_color(*BLACK)
        if subtitle:
            self.ln(12)
            self.set_font("Helvetica", "I", 9)
            self.set_text_color(*GRAY)
            self.set_x(20)
            self.cell(0, 6, subtitle)
            self.set_text_color(*BLACK)
        self.ln(14)

    def subsection(self, title: str):
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(*BLUE)
        self.set_x(20)
        self.cell(0, 8, title)
        self.ln(9)
        self.set_text_color(*BLACK)

    def body_text(self, text: str):
        self.set_font("Helvetica", "", 10)
        self.set_text_color(*BLACK)
        self.set_x(20)
        self.multi_cell(170, 6, text)
        self.ln(4)

    def metric_card(self, label: str, value: str, unit: str = "", color=BLUE):
        x = self.get_x()
        y = self.get_y()
        self.set_fill_color(*LGRAY)
        self.rect(x, y, 55, 22, "F")
        self.set_fill_color(*color)
        self.rect(x, y, 55, 3, "F")
        self.set_font("Helvetica", "B", 16)
        self.set_text_color(*color)
        self.set_xy(x + 2, y + 4)
        self.cell(51, 10, value, align="C")
        self.set_font("Helvetica", "", 7)
        self.set_text_color(*GRAY)
        self.set_xy(x + 2, y + 14)
        self.cell(51, 4, unit, align="C")
        self.set_xy(x + 2, y + 18)
        self.cell(51, 4, label.upper(), align="C")
        self.set_text_color(*BLACK)

    def alert_box(self, text: str, severity: str):
        colors = {
            "critical": (183, 28,  28),
            "high":     (230, 81,   0),
            "medium":   (245, 127,  23),
            "low":      (21, 101, 192),
        }
        color = colors.get(severity, colors["low"])
        self.set_fill_color(*color)
        self.rect(20, self.get_y(), 3, 10, "F")
        self.set_fill_color(*(tuple(min(c + 200, 255) for c in color)))
        self.rect(23, self.get_y(), 167, 10, "F")
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(*color)
        self.set_xy(26, self.get_y() + 1.5)
        label = severity.upper()
        self.cell(20, 7, f"[{label}]")
        self.set_font("Helvetica", "", 9)
        self.set_text_color(*BLACK)
        self.cell(0, 7, text[:100])
        self.ln(12)

    def table_header(self, cols: list, widths: list):
        self.set_fill_color(*NAVY)
        self.set_text_color(*WHITE)
        self.set_font("Helvetica", "B", 9)
        self.set_x(20)
        for col, w in zip(cols, widths):
            self.cell(w, 8, col, border=0, fill=True, align="C")
        self.ln(8)
        self.set_text_color(*BLACK)

    def table_row(self, values: list, widths: list, fill=False):
        self.set_fill_color(*LGRAY)
        self.set_font("Helvetica", "", 9)
        self.set_x(20)
        for val, w in zip(values, widths):
            self.cell(w, 7, str(val), border=0, fill=fill, align="C")
        self.ln(7)

    def divider(self):
        self.set_draw_color(*TEAL)
        self.set_line_width(0.5)
        self.line(20, self.get_y(), 190, self.get_y())
        self.set_draw_color(0, 0, 0)
        self.set_line_width(0.2)
        self.ln(4)


# ─────────────────────────────────────────────────────────────────────────────
# MAIN BUILD FUNCTION
# ─────────────────────────────────────────────────────────────────────────────

def build_pdf(
    analysis: dict,
    quality: dict,
    report: dict,
    recommendations: dict,
    company_name: str,
    reporting_year: str,
    output_path: str,
) -> str:
    pdf = AquaMindReport(company_name, reporting_year)

    # ── COVER ─────────────────────────────────────────────────────────────────
    pdf.cover_page()

    # ── PAGE 2: KEY METRICS ────────────────────────────────────────────────────
    pdf.add_page()
    pdf.section_title("Key Performance Metrics", f"Reporting Period: {analysis.get('reporting_period', reporting_year)}")

    # Metric cards — row 1
    pdf.set_x(20)
    y = pdf.get_y()
    total_m3  = f"{analysis.get('total_consumption_m3', 0):,.0f}"
    total_usd = f"${analysis.get('total_cost_usd', 0):,.0f}"
    facilities = str(analysis.get('facilities_analyzed', 3))

    pdf.set_xy(20, y)
    pdf.metric_card("Total Water Withdrawn", total_m3, "cubic meters", BLUE)
    pdf.set_xy(80, y)
    pdf.metric_card("Total Water Cost", total_usd, "USD", TEAL)
    pdf.set_xy(140, y)
    pdf.metric_card("Facilities Monitored", facilities, "sites", NAVY)
    pdf.ln(32)

    # Quality score card
    q_score = quality.get("quality_score", 0)
    q_status = quality.get("overall_quality_status", "WATCH")
    status_color = {"COMPLIANT": TEAL, "WATCH": (230, 81, 0), "ALERT": (183, 28, 28), "CRITICAL": (183, 28, 28)}.get(q_status, BLUE)
    y2 = pdf.get_y()
    pdf.set_xy(20, y2)
    pdf.metric_card("Quality Score", str(q_score), "out of 100", status_color)
    pdf.set_xy(80, y2)
    alert_count = len(quality.get("alerts", []))
    pdf.metric_card("Quality Alerts", str(alert_count), "readings flagged", status_color)
    rec_savings = recommendations.get("total_potential_savings_m3_annual", 0)
    pdf.set_xy(140, y2)
    pdf.metric_card("Potential Savings", f"{rec_savings:,.0f}", "m³/year identified", TEAL)
    pdf.ln(32)

    # Executive summary
    pdf.subsection("Executive Summary")
    exec_summary = report.get("sections", {}).get("executive_summary", analysis.get("executive_summary", ""))
    pdf.body_text(exec_summary)

    # ── PAGE 3: CONSUMPTION ANALYSIS ───────────────────────────────────────────
    pdf.add_page()
    pdf.section_title("Water Consumption Analysis", "GRI 303-3: Water Withdrawal  •  GRI 303-5: Water Consumption")

    # GRI 303-5 disclosure
    pdf.subsection("GRI 303-5: Water Consumption")
    gri_305 = report.get("sections", {}).get("gri_303_5_water_consumption", "")
    pdf.body_text(gri_305 if gri_305 else analysis.get("executive_summary", ""))

    # Facility breakdown table
    pdf.subsection("Withdrawal by Facility")
    fb = analysis.get("facility_breakdown", [])
    if fb:
        pdf.table_header(["Facility", "Total (m³)", "Avg Monthly (m³)", "% of Total", "Trend"], [65, 30, 40, 25, 20])
        for i, f in enumerate(fb):
            pdf.table_row([
                f.get("facility", "")[:30],
                f"{f.get('total_m3', 0):,.0f}",
                f"{f.get('avg_monthly_m3', 0):,.0f}",
                f"{f.get('share_of_total_pct', 0):.1f}%",
                f.get("trend", "").capitalize(),
            ], [65, 30, 40, 25, 20], fill=(i % 2 == 0))
    pdf.ln(4)

    # Anomalies
    anomalies = analysis.get("anomalies", [])
    if anomalies:
        pdf.subsection("Consumption Anomalies Detected")
        for a in anomalies:
            severity = a.get("severity", "medium")
            text = (f"{a.get('facility')} – {a.get('month')}: "
                    f"{a.get('consumption_m3'):,.0f} m³ detected (expected ~{a.get('expected_m3'):,.0f} m³, "
                    f"+{a.get('deviation_pct', 0):.0f}%). Likely cause: {a.get('likely_cause', '')}")
            pdf.alert_box(text, severity)

    # GRI 303-1
    pdf.subsection("GRI 303-1: Water as a Shared Resource")
    pdf.body_text(report.get("sections", {}).get("gri_303_1_water_interactions", ""))

    # ── PAGE 4: WATER QUALITY ───────────────────────────────────────────────────
    pdf.add_page()
    pdf.section_title("Water Quality & Security Monitoring", "EPA SDWA Compliance  •  AquaQuality Agent Findings")

    pdf.subsection(f"Overall Quality Status: {q_status}  |  Score: {q_score}/100")
    pdf.body_text(quality.get("compliance_statement", ""))

    # Parameters summary table
    params = quality.get("parameters_summary", [])
    if params:
        pdf.subsection("Parameter Summary (All Facilities, All Months)")
        pdf.table_header(["Parameter", "Average", "Min", "Max", "Compliant %", "Status"], [40, 25, 25, 25, 30, 25])
        status_labels = {"compliant": "OK", "watch": "WATCH", "alert": "ALERT"}
        for i, p in enumerate(params):
            pdf.table_row([
                p.get("parameter", "").replace("_", " ").title(),
                str(round(p.get("avg_value", 0), 2)),
                str(round(p.get("min_value", 0), 2)),
                str(round(p.get("max_value", 0), 2)),
                f"{p.get('compliant_readings_pct', 100):.0f}%",
                status_labels.get(p.get("status", "compliant"), "OK"),
            ], [40, 25, 25, 25, 30, 25], fill=(i % 2 == 0))
    pdf.ln(4)

    # Quality alerts
    alerts = quality.get("alerts", [])
    if alerts:
        pdf.subsection("Quality Alerts Requiring Action")
        for a in alerts:
            text = (f"{a.get('facility')} – {a.get('month')}: "
                    f"{a.get('parameter', '').replace('_', ' ').title()} = {a.get('value')} "
                    f"(threshold: {a.get('threshold_type', 'max')} {a.get('threshold')} per {a.get('regulatory_standard', 'EPA')}). "
                    f"Action: {a.get('recommended_action', '')}")
            pdf.alert_box(text, a.get("severity", "medium"))

    # Security observations
    security_obs = quality.get("security_observations", [])
    if security_obs:
        pdf.subsection("Security & Integrity Observations")
        for obs in security_obs:
            pdf.body_text(f"• {obs}")

    # ── PAGE 5: ESG DISCLOSURES ─────────────────────────────────────────────────
    pdf.add_page()
    pdf.section_title("ESG Disclosures", "GRI 303 Water and Effluents  •  CDP Water Security")

    gri_sec = report.get("sections", {})
    for section_key, section_title in [
        ("gri_303_3_water_withdrawal",  "GRI 303-3: Water Withdrawal"),
        ("gri_303_4_water_discharge",   "GRI 303-4: Water Discharge"),
        ("quality_and_compliance",      "Quality and Regulatory Compliance"),
        ("risk_assessment",             "Water Risk Assessment"),
        ("management_approach",         "Management Approach and Governance"),
    ]:
        content = gri_sec.get(section_key, "")
        if content:
            pdf.subsection(section_title)
            pdf.body_text(content)
            pdf.divider()

    # Key metrics table
    key_metrics = report.get("key_metrics_table", [])
    if key_metrics:
        pdf.subsection("Key Reported Metrics")
        pdf.table_header(["Metric", "Value", "Framework Reference"], [90, 50, 30])
        for i, m in enumerate(key_metrics):
            pdf.table_row([
                m.get("metric", "")[:50],
                m.get("value", ""),
                m.get("framework", ""),
            ], [90, 50, 30], fill=(i % 2 == 0))

    # ── PAGE 6: RECOMMENDATIONS ─────────────────────────────────────────────────
    pdf.add_page()
    pdf.section_title("AI-Generated Recommendations", "Prioritized by impact and ease of implementation")

    total_savings_m3  = recommendations.get("total_potential_savings_m3_annual", 0)
    total_savings_usd = recommendations.get("total_potential_savings_usd_annual", 0)
    pdf.subsection(f"Total Identified Savings Potential: {total_savings_m3:,.0f} m³/year  |  ${total_savings_usd:,.0f}/year")

    recs = recommendations.get("recommendations", [])
    effort_color = {"low": TEAL, "medium": BLUE, "high": NAVY}

    for r in recs:
        priority = r.get("priority", 0)
        title    = r.get("title", "")
        facility = r.get("facility", "All Facilities")
        effort   = r.get("implementation_effort", "medium")
        timeline = r.get("implementation_timeline", "")
        sav_m3   = r.get("estimated_savings_m3_annual", 0)
        sav_usd  = r.get("estimated_savings_usd_annual", 0)
        roi      = r.get("roi_months", "")
        desc     = r.get("description", "")
        reg      = r.get("relevant_regulation", "")

        # Priority badge
        pdf.set_fill_color(*BLUE)
        pdf.set_text_color(*WHITE)
        pdf.set_font("Helvetica", "B", 9)
        y_rec = pdf.get_y()
        pdf.rect(20, y_rec, 10, 10, "F")
        pdf.set_xy(20, y_rec + 1.5)
        pdf.cell(10, 7, f"#{priority}", align="C")

        # Title
        pdf.set_text_color(*NAVY)
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_xy(33, y_rec + 1)
        pdf.cell(0, 7, f"{title}  —  {facility}")
        pdf.ln(10)

        # Description
        pdf.set_text_color(*BLACK)
        pdf.set_font("Helvetica", "", 10)
        pdf.set_x(33)
        pdf.multi_cell(155, 6, desc)
        pdf.ln(2)

        # Stats row
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(*GRAY)
        pdf.set_x(33)
        stats = f"Effort: {effort.upper()}  |  Timeline: {timeline}  |  ROI: {roi} months  |  Savings: {sav_m3:,.0f} m³/yr  =  ${sav_usd:,.0f}/yr"
        if reg:
            stats += f"  |  Regulation: {reg}"
        pdf.cell(0, 5, stats)
        pdf.ln(5)
        pdf.divider()

    # ── PAGE 7: METHODOLOGY ────────────────────────────────────────────────────
    pdf.add_page()
    pdf.section_title("Methodology & About AquaMind")

    pdf.subsection("About This Report")
    pdf.body_text(
        "This report was generated entirely by AquaMind's autonomous AI agent pipeline. "
        "Data was ingested, validated, and processed by four specialized AI agents running in sequence: "
        "the Data Intelligence Agent (consumption analysis and anomaly detection), the Water Quality & Security "
        "Agent (regulatory threshold monitoring), the ESG Report Writer Agent (GRI/CDP narrative generation), "
        "and the Recommendations Agent (quantified optimization opportunities). "
        "Human review of AI-generated content is recommended before external publication."
    )

    pdf.subsection("Data Collection Methodology")
    pdf.body_text(
        "Water consumption data was collected from facility meters and utility bills. "
        "Quality parameters were recorded by on-site sensors and manual sampling where indicated. "
        "All data represents actual metered readings unless otherwise noted. "
        "Anomaly detection uses a statistical threshold of 25% deviation from 3-month rolling average baseline."
    )

    pdf.subsection("Regulatory Frameworks Applied")
    pdf.body_text(
        "GRI 303 (2018): Water and Effluents standard, disclosures 303-1 through 303-5. "
        "CDP Water Security: Modules W1 (Current State Assessment) and W4 (Risks and Opportunities). "
        "EPA Safe Drinking Water Act: Maximum Contaminant Levels for pH, turbidity, chlorine, and nitrates. "
        "TCFD: Task Force on Climate-related Financial Disclosures, water-related physical risk factors."
    )

    pdf.subsection("Benchmarking Sources")
    pdf.body_text(
        "Industry water intensity benchmarks sourced from: Pacific Institute Water Benchmarking Initiative, "
        "CDP Water Security Sector Scores (2024), EPA WaterSense Program, and World Resources Institute "
        "Aqueduct Water Risk Atlas sector averages."
    )

    pdf.divider()
    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(*GRAY)
    pdf.set_x(20)
    pdf.multi_cell(170, 6,
        "DISCLAIMER: This report was generated by artificial intelligence and should be reviewed by a qualified "
        "sustainability professional before being submitted to regulators, investors, or disclosed publicly. "
        "AquaMind makes no warranty regarding the completeness or accuracy of AI-generated content."
    )

    pdf.output(output_path)
    return output_path
